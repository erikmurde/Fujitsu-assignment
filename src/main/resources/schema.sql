-- SQL file for setting up the structure of the database.
-- Tables are only created if they do not already exist.

-- Table for storing city information
CREATE TABLE IF NOT EXISTS city (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

-- Table for storing vehicle type information
CREATE TABLE IF NOT EXISTS vehicle_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

-- Table for storing weather observations
CREATE TABLE IF NOT EXISTS observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    wmo_code INTEGER NOT NULL,
    air_temperature FLOAT NOT NULL,
    wind_speed FLOAT NOT NULL,
    phenomenon VARCHAR(255) NOT NULL,
    timestamp INTEGER NOT NULL,
    FOREIGN KEY (city_id) REFERENCES city(id)
);

-- Table for storing regional base fees
CREATE TABLE IF NOT EXISTS regional_base_fee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 20) PRIMARY KEY,
    city_id BIGINT NOT NULL,
    vehicle_type_id BIGINT NOT NULL,
    amount FLOAT NOT NULL,
    FOREIGN KEY (city_id) REFERENCES city(id),
    FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_type(id)
);